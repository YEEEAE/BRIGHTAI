/**
 * @brightai/dashboard — AsyncLocalStorage-based request context.
 *
 * P0-3 (2026-07-19): request IDs and org/user context propagation.
 *
 * Why AsyncLocalStorage (ALS):
 *   - The dashboard has ~30 routes + middleware. Propagating context
 *     through every function signature is impractical.
 *   - ALS gives us a per-request store that's automatically restored
 *     across async boundaries (await, Promise.all, setTimeout, etc.)
 *   - Works with Next.js middleware → server component → server action
 *     chains without manual plumbing.
 *
 * The middleware sets the context once per request; logger.ts and
 * the firewall audit layer read it via `getRequestContext()`.
 *
 * Limits:
 *   - ALS does NOT cross worker boundaries (each Node worker has its
 *     own store). For multi-process deployments, propagate the
 *     request ID via a header (X-Request-Id) and re-set the context
 *     on the other side.
 *   - The context is per-async-chain. A `setTimeout` callback has the
 *     same context as the caller (good); a fresh `Promise.resolve()`
 *     chain does not (expected).
 */

import { AsyncLocalStorage } from 'node:async_hooks';

export type RequestContext = {
  /** Unique request ID (generated by middleware or test setup). */
  requestId: string;
  /** Organization ID (if auth resolved a tenant). May be undefined. */
  organizationId?: string;
  /** User ID (if auth resolved a user). May be undefined. */
  userId?: string;
  /** Request path (for log correlation). */
  path?: string;
  /** HTTP method. */
  method?: string;
  /** When the context was created. */
  startedAt: number;
};

const storage = new AsyncLocalStorage<RequestContext>();

/**
 * Run `fn` inside a request context. The context is restored across
 * any async boundaries within `fn`. Use this in middleware or
 * anywhere you need to scope a request.
 */
export function runWithRequestContext<T>(
  ctx: RequestContext,
  fn: () => T | Promise<T>,
): T | Promise<T> {
  return storage.run(ctx, fn) as T | Promise<T>;
}

/** Get the current request context (or undefined if not in a request). */
export function getRequestContext(): RequestContext | undefined {
  return storage.getStore();
}

/** Get the request ID, or a placeholder if no context is set. */
export function getRequestId(): string {
  return storage.getStore()?.requestId ?? 'no-request';
}

/** Get the org-scoped context subset (org + user) for log/Sentry. */
export function getOrgContext(): { organizationId?: string; userId?: string } {
  const ctx = storage.getStore();
  return {
    organizationId: ctx?.organizationId,
    userId: ctx?.userId,
  };
}
