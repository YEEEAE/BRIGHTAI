-- QC Laboratory Equipment calibration flag (PROMPT 11).
--
-- The canonical 24-device equipment registry carries a calibration
-- "yes"/"no" value per row (page reference §32 + additions A2). lab_equipment
-- (011) has no column for it, so this additive migration stores the supplied
-- value VERBATIM (D-1). Display and filtering map it at read time
-- (src/lib/lab/equipmentStatus.ts) and the stored text is never rewritten.
--
-- Derived calibration state from dated records (lab_equipment_calibration,
-- 011) stays a separate concept: this flag is the registry's own field, while
-- the register's due-state is computed from lab_equipment_calibration dates.
ALTER TABLE lab_equipment ADD COLUMN calibration_status_raw TEXT;