-- In-app notifications — entity deep links (/lab/notifications, PROMPT 26).
--
-- The global bell links every persisted notification at /tasks/<id> (or the
-- notifications page when task_id is NULL). Laboratory notifications carry
-- task_id NULL by design (lab events are not tasks), so they all fell back to
-- the notifications page. entity_href stores the REAL source-record link
-- written by the same transaction that writes the notification (e.g.
-- /lab/tests/12, /lab/equipment/3, /lab/retests/4, /lab/acknowledgements)
-- and the notification layers prefer it over the legacy task link. NULL keeps
-- the previous behaviour for every pre-existing row.
ALTER TABLE notifications ADD COLUMN entity_href TEXT;
