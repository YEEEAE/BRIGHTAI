import test from 'node:test';
import assert from 'node:assert/strict';
import {
  canTransitionTrial,
  deriveTrialState,
  trialAccessFor,
  commercialAccessModel,
  TRIAL_DURATION_SECONDS,
  TRIAL_POLICY,
} from '../src/server/kernel/trial.mjs';

// P06-A unit contract: the pure state machine and projection. No DB, no network.
test('P06-A trial: 48h window, state machine and commercial separation', () => {
  assert.equal(TRIAL_DURATION_SECONDS, 172800);
  assert.equal(TRIAL_POLICY.startField, 'activated_at');
  assert.equal(TRIAL_POLICY.durationSeconds, 172800);
  // No price, renewal, checkout or automatic conversion exists in the policy.
  assert.equal(TRIAL_POLICY.conversion.price, null);
  assert.equal(TRIAL_POLICY.conversion.automatic, false);
  assert.equal(TRIAL_POLICY.renewal.automatic, false);
  assert.equal(TRIAL_POLICY.exit.deletionExecuted, false);
  assert.equal(TRIAL_POLICY.exit.retentionPeriod, null);
  assert.equal(TRIAL_POLICY.proofOfValue.autoGenerated, false);

  // Allowed path, each step by its own actor.
  assert.equal(canTransitionTrial('REQUESTED', 'ELIGIBILITY_REVIEW', { actor: 'TENANT' }).allowed, true);
  assert.equal(canTransitionTrial('ELIGIBILITY_REVIEW', 'APPROVED', { actor: 'OPERATOR' }).allowed, true);
  const activation = { actor: 'OPERATOR', readinessVerified: true, dataMode: 'SYNTHETIC', customerAcknowledged: true };
  assert.equal(canTransitionTrial('APPROVED', 'ACTIVATED', activation).allowed, true);
  assert.equal(canTransitionTrial('ACTIVATED', 'EXPIRED', { actor: 'SYSTEM' }).allowed, true);

  // Rejections the cycle must never allow.
  assert.equal(canTransitionTrial('EXPIRED', 'ACTIVATED', activation).code, 'TRANSITION_NOT_ALLOWED');
  assert.equal(canTransitionTrial('REQUESTED', 'APPROVED', { actor: 'OPERATOR' }).code, 'TRANSITION_NOT_ALLOWED');
  assert.equal(canTransitionTrial('ELIGIBILITY_REVIEW', 'APPROVED', { actor: 'TENANT' }).code, 'OPERATOR_DECISION_REQUIRED');
  assert.equal(canTransitionTrial('APPROVED', 'ACTIVATED', { actor: 'TENANT', readinessVerified: true, dataMode: 'SYNTHETIC', customerAcknowledged: true }).code, 'OPERATOR_ACTIVATION_REQUIRED');
  assert.equal(canTransitionTrial('APPROVED', 'ACTIVATED', { actor: 'OPERATOR', readinessVerified: false, dataMode: 'SYNTHETIC', customerAcknowledged: true }).code, 'READINESS_NOT_VERIFIED');
  assert.equal(canTransitionTrial('APPROVED', 'ACTIVATED', { actor: 'OPERATOR', readinessVerified: true, dataMode: 'CUSTOMER', customerAcknowledged: true }).code, 'SYNTHETIC_DATA_ONLY');
  assert.equal(canTransitionTrial('APPROVED', 'ACTIVATED', { actor: 'OPERATOR', readinessVerified: true, dataMode: 'SYNTHETIC', customerAcknowledged: false }).code, 'CUSTOMER_ACKNOWLEDGEMENT_REQUIRED');
  assert.equal(canTransitionTrial('ACTIVATED', 'EXPIRED', { actor: 'TENANT' }).code, 'SYSTEM_CLOCK_REQUIRED');
  assert.equal(canTransitionTrial('ELIGIBILITY_REVIEW', 'REJECTED', { actor: 'OPERATOR', reason: 'short' }).code, 'OPERATOR_REASON_REQUIRED');
  assert.equal(canTransitionTrial('REQUESTED', 'CANCELLED', { actor: 'TENANT', reason: 'short' }).code, 'CANCELLATION_REASON_REQUIRED');
  assert.equal(canTransitionTrial('UNKNOWN', 'ACTIVATED', {}).code, 'INVALID_STATE');
});

test('P06-A trial: the window starts at activated_at and expiry is derived, not trusted', () => {
  const now = Date.UTC(2026, 10, 10, 12, 0, 0);
  const activatedAt = new Date(now - 60_000).toISOString();
  const expiresAt = new Date(now - 60_000 + 172_800_000).toISOString();
  assert.equal(deriveTrialState({ state: 'ACTIVATED', activated_at: activatedAt, expires_at: expiresAt }, now), 'ACTIVATED');
  assert.equal(deriveTrialState({ state: 'ACTIVATED', activated_at: activatedAt, expires_at: expiresAt }, now + 172_800_000), 'EXPIRED');
  // A window that is not exactly 48h is an invalid configuration, never a grace period.
  assert.equal(deriveTrialState({ state: 'ACTIVATED', activated_at: activatedAt, expires_at: new Date(now + 1_000).toISOString() }, now), 'INVALID_CONFIGURATION');
  assert.equal(deriveTrialState({ state: 'APPROVED' }, now), 'APPROVED');
  assert.equal(deriveTrialState({ state: 'WHAT' }, now), 'INVALID_CONFIGURATION');
  assert.equal(deriveTrialState(null, now), 'NONE');
});

test('P06-A trial: access projection never turns a request or approval into access', () => {
  const base = { configured: true, products: ['firewall'], entitledProducts: [], state: 'APPROVED' };
  assert.equal(trialAccessFor(base, 'firewall').grantsProduct, false);
  assert.equal(trialAccessFor(base, 'firewall').reason, 'ACTIVATION_NOT_COMPLETED');
  assert.equal(trialAccessFor({ ...base, state: 'ACTIVATED', entitledProducts: [] }, 'firewall').grantsProduct, false);
  assert.equal(trialAccessFor({ ...base, state: 'ACTIVATED', entitledProducts: ['firewall'] }, 'firewall').grantsProduct, true);
  assert.equal(trialAccessFor(base, 'ledger').state, 'NOT_INCLUDED');
  assert.equal(trialAccessFor({ configured: false, reason: 'MIGRATION_0023_NOT_APPLIED' }, 'firewall').state, 'NOT_CONFIGURED');
  assert.equal(trialAccessFor({ ...base, state: 'EXPIRED' }, 'firewall').state, 'EXPIRED');
  assert.equal(trialAccessFor({ ...base, state: 'INVALID_CONFIGURATION' }, 'firewall').state, 'BLOCKED');

  const model = commercialAccessModel('ACTIVE', 'EXPIRED');
  assert.equal(model.administrative.grantsProduct, true);
  assert.equal(model.trial.grantsProduct, false);
  assert.equal(model.expired.administrative, false);
  assert.equal(model.expired.trial, true);
  assert.equal(model.subscription.grantsProduct, false);
  assert.equal(model.license.state, 'NOT_CONFIGURED');
});
