#!/usr/bin/env node
/**
 * Verifies the standalone Astro artifact exposes only its intended HTTP surface.
 *
 * BAI-SEC-10 (2026-07-25) — extended from the 3-route smoke test to a
 * comprehensive deny-list check. The deny-list is the same one enforced
 * at runtime by `src/server/deny-list.mjs` (deployed as
 * `dist/server/_deny-list.mjs` and wired into `dist/server/entry.mjs`).
 *
 * Behavior:
 *   - Starts `dist/server/entry.mjs` on a loopback-only dedicated port.
 *   - For each (path, expectedStatus) in `checks`:
 *       - Performs HEAD (with `redirect: 'manual'` so we observe the
 *         actual code Render's reverse proxy would observe).
 *       - Asserts the response status matches the expected one.
 *   - Exits 1 on any mismatch.
 *   - Exits 0 when every check passes.
 *
 * Why HEAD and not GET:
 *   - GET would stream the body. We only need the status code. HEAD is
 *     cheaper and avoids any side effects from endpoint handlers.
 *   - The standalone server (Node http) handles HEAD the same as GET
 *     (it strips the body), so this is reliable.
 *
 * Why loopback only (127.0.0.1):
 *   - Avoids exposing the unauthenticated test instance to the network.
 *   - The CI host is trusted; we only need to verify the Node layer
 *     behavior. Edge caching (Cloudflare) is verified separately by
 *     `verify:live:headers` against brightai.site.
 *
 * Integration:
 *   - `pnpm run verify:deployment-surface` is the preDeployCommand on
 *     Render (see render.yaml). If this exits 1, the deploy is blocked.
 *   - Add new public paths to `PUBLIC_SURFACE` below so future KIs
 *     (e.g. new top-level sections) keep the verifier aligned.
 */
import { spawn } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const root = path.resolve(path.dirname(__filename), '..');
const entry = path.join(root, 'dist', 'server', 'entry.mjs');
const port = 4317;
const baseUrl = `http://127.0.0.1:${port}`;

/**
 * PUBLIC_SURFACE — paths that MUST return 2xx (or 301/308 for trailing
 * slash redirects). These are sanity checks that we did not break the
 * public surface while adding the deny-list. They are NOT exhaustive —
 * the full site has 196 pages, but a representative sample is enough
 * to catch blanket regressions (e.g. middleware always-404).
 */
const PUBLIC_SURFACE = [
  ['/', 200],
  ['/about/', 200],
  ['/services/', 200],
  ['/pricing/', 200],
  ['/contact/', 200],
  ['/blog/', 200],
  ['/docs/', 200],
  ['/solutions/', 200],
  ['/solutions/ai-governance-platform/', 200],
  ['/solutions/banking-ai-governance/riyadh/', 200],
  ['/en/privacy-policy/', 200],
  ['/robots.txt', 200],
  ['/sitemap.xml', 200],
  ['/favicon.svg', 200],
  ['/icons.svg', 200],
  ['/manifest.webmanifest', 200],
  ['/llms.txt', 200],
  ['/humans.txt', 200],
  ['/e158df443f2742d281a02c4aeecb4a60.txt', 200],
  ['/_astro/', 404], // _astro/ is a dir — index is generated by hashes
  ['/api/health/', 200],
  ['/api/ai/chat/', 200], // accepts POST; HEAD may 404/405 — see note below
  ['/api/csrf-token/', 200], // trailing slash canonical form
];

/**
 * DENY_LIST_SURFACE — paths that MUST return 404. These are the canonical
 * forbidden surfaces from BAI-SEC-10 + the patterns in
 * `src/server/deny-list.mjs`. If ANY of these returns 2xx, the build
 * artifact is leaking source code, secrets, or repo metadata.
 *
 * The list is split by category so the output is easy to read on failure.
 */
const DENY_LIST_SURFACE = [
  // A. Backend source code that was historically leaked (BAI-SEC-10)
  ['/frontend/server.js', 404],
  ['/frontend/config.js', 404],
  ['/frontend/db/init.js', 404],
  ['/frontend/routes/chat.js', 404],
  ['/frontend/middleware/productionSecrets.js', 404],
  ['/frontend/middleware/rateLimiter.js', 404],
  ['/frontend/services/staticFiles.js', 404],
  ['/frontend/package.json', 404],
  // B. Accidental top-level static dirs from old Next.js / Vite era
  ['/client/index.html', 404],
  ['/server/entry.mjs', 404],
  ['/package.json', 404],
  // C. Repo metadata that must never be served
  ['/.env', 404],
  ['/.env.local', 404],
  ['/.env.production', 404],
  ['/.agents/brain.md', 404],
  ['/.agents/skills/README.md', 404],
  ['/astro.config.mjs', 404],
  ['/render.yaml', 404],
  ['/Dockerfile', 404],
  ['/docker-compose.yml', 404],
  ['/AGENTS.md', 404],
  ['/CLAUDE.md', 404],
  ['/tsconfig.json', 404],
  ['/pnpm-lock.yaml', 404],
  ['/opencode.json', 404],
  ['/scripts/', 404],
  ['/src/', 404],
  ['/packages/', 404],
  ['/apps/', 404],
  // D. /report/ — Render routes /report, /report.html, /report/index.html
  //    to /trust/ at the edge, so a request reaching the Node server
  //    for /report/ should be 404 (no file) or 404 (deny-list).
  ['/report/', 404],
  ['/report/some-archive.html', 404],
  // E. Legacy Next.js / Vite client metadata (defensive)
  ['/_next/static/foo.js', 404],
  ['/next.config.mjs', 404],
  // F. Build internals that must never be served
  ['/_astro-internals/', 404],
];

/**
 * checks — the merged list the verifier runs. Public surface first
 * (sanity), then deny-list (security). Public checks come first so
 * if the public site is broken we surface that as the primary error.
 *
 * Per-row tolerance rules (applied in the loop below):
 *   - For PUBLIC_SURFACE rows: we hit the canonical (trailing-slash)
 *     form when applicable to avoid `trailingSlash: 'always'` 301s.
 *     API endpoints may return 405 on HEAD — we treat that as a pass
 *     because the endpoint exists and is wired up.
 *   - For DENY_LIST_SURFACE rows: 200 (or any 2xx) is a HARD FAIL —
 *     the file is being served. 301/302/307/308/404/410 are all PASS
 *     because they confirm the deny-list or the file-not-found path
 *     is enforced (even a 301 to /Dockerfile/ that then 404s is OK).
 */
const checks = [...PUBLIC_SURFACE, ...DENY_LIST_SURFACE];

if (!existsSync(entry)) {
  console.error('[verify-deployment-surface] dist/server/entry.mjs is missing. Run pnpm build first.');
  process.exit(1);
}

// Sanity: also verify the deny-list module is present in dist/server/
// (the patcher should have written it as part of the build). If it's
// missing, the deny-list is NOT enforced at runtime — the verifier would
// pass against an unwrapped server, which defeats the purpose.
const denyListDeployed = path.join(root, 'dist', 'server', '_deny-list.mjs');
if (!existsSync(denyListDeployed)) {
  console.error(
    '[verify-deployment-surface] dist/server/_deny-list.mjs is missing. The Node handler is NOT ' +
    'wrapped with the deny-list. This is a BAI-SEC-10 regression — the build:patch-entry step ' +
    'did not run. Aborting.'
  );
  process.exit(1);
}

// Sanity: verify the entry.mjs references BAI-SEC-10 (defense in
// depth — catches cases where the patcher is skipped or future changes
// remove the wrapper). The actual deny-list check lives in the chunk
// file (chunks/server_<HASH>.mjs); entry.mjs gets a marker import to
// make the patcher's presence discoverable from the entry file.
const entryContent = readFileSync(entry, 'utf-8');
if (!entryContent.includes('BAI-SEC-10')) {
  console.error(
    '[verify-deployment-surface] dist/server/entry.mjs does not reference BAI-SEC-10. The ' +
    'patcher did not run. This is a BAI-SEC-10 regression. Aborting.'
  );
  process.exit(1);
}

// Sanity: also verify the chunk file has the deny-list listener patch.
// The chunk filename is hashed; we discover it from the entry.mjs import.
const chunkImportMatch = entryContent.match(/from\s*['"]\.\/chunks\/(server_[A-Za-z0-9_-]+\.mjs)['"]/);
if (!chunkImportMatch) {
  console.error(
    '[verify-deployment-surface] could not find the @astrojs/node server chunk in entry.mjs. ' +
    'The patcher expected ./chunks/server_<HASH>.mjs but entry.mjs format changed.'
  );
  process.exit(1);
}
const chunkPath = path.join(root, 'dist', 'server', 'chunks', chunkImportMatch[1]);
if (!existsSync(chunkPath)) {
  console.error(
    `[verify-deployment-surface] chunk file not found at ${chunkPath} — did astro build run?`
  );
  process.exit(1);
}
const chunkContent = readFileSync(chunkPath, 'utf-8');
if (!chunkContent.includes('BAI-SEC-10:deny-list')) {
  console.error(
    `[verify-deployment-surface] ${chunkImportMatch[1]} does not contain the BAI-SEC-10:deny-list marker. ` +
    'The listener-level deny-list patch is NOT in place. This is a BAI-SEC-10 regression. Aborting.'
  );
  process.exit(1);
}

const child = spawn(process.execPath, [entry], {
  cwd: root,
  env: {
    ...process.env,
    HOST: '127.0.0.1',
    PORT: String(port),
    // Provide a stable CSRF_SECRET for the loopback test so the
    // /api/csrf-token/ endpoint can mint a token. Production uses a
    // real secret from Render env; the verifier just needs the endpoint
    // to be reachable.
    CSRF_SECRET: process.env.CSRF_SECRET || 'verify-deployment-surface-test-secret-32chars+',
  },
  stdio: 'ignore',
});

function stopServer() {
  if (!child.killed) child.kill('SIGTERM');
}

async function waitForServer() {
  const deadline = Date.now() + 10_000;
  while (Date.now() < deadline) {
    try {
      const response = await fetch(`${baseUrl}/`, { method: 'HEAD' });
      if (response.status > 0) return;
    } catch {
      // The process may still be binding its listener.
    }
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  throw new Error('standalone server did not become ready within 10 seconds');
}

let failed = 0;
let passed = 0;
const failures = [];

try {
  await waitForServer();

  for (const [route, expectedStatus] of checks) {
    const response = await fetch(`${baseUrl}${route}`, { method: 'HEAD', redirect: 'manual' });
    const actual = response.status;
    const isDenyRow = DENY_LIST_SURFACE.some(([r]) => r === route);

    // ── Public surface tolerance ──
    // Some API endpoints reject HEAD with 405 (method-not-allowed).
    // We treat 405 on a /api/* PUBLIC_SURFACE row as a pass because
    // the endpoint exists and is wired up — we just can't probe it
    // with HEAD.
    if (!isDenyRow && expectedStatus === 200 && actual === 405 && route.startsWith('/api/')) {
      console.log(`[verify-deployment-surface] ✅ ${route} -> 405 (treated as pass; HEAD not allowed on POST endpoint)`);
      passed += 1;
      continue;
    }

    // ── Deny-list tolerance ──
    // For DENY_LIST_SURFACE rows: a 2xx is a HARD FAIL (file is being
    // served). Anything else is a pass:
    //   - 301/302/307/308 (redirect) is OK because the file is not
    //     being served. trailingSlash may redirect /Dockerfile →
    //     /Dockerfile/ which then 404s; that's fine.
    //   - 404 is the expected deny-list path.
    //   - 410 (gone) would also be acceptable.
    if (isDenyRow) {
      if (actual >= 200 && actual < 300) {
        // LEAK! This is the only hard fail.
        failed += 1;
        failures.push({ route, actual, expectedStatus, leak: true });
        console.error(`[verify-deployment-surface] ❌ LEAK ${route} -> ${actual} (expected non-2xx; got 2xx — file is being served!)`);
      } else {
        passed += 1;
        const tag = actual === expectedStatus ? '✅' : '✓';
        console.log(`[verify-deployment-surface] ${tag} ${route} -> ${actual} (deny-list enforced)`);
      }
      continue;
    }

    // ── Strict public-surface match ──
    const pass = actual === expectedStatus;
    const tag = pass ? '✅' : '❌';
    console.log(`[verify-deployment-surface] ${tag} ${route} -> ${actual} (expected ${expectedStatus})`);

    if (pass) {
      passed += 1;
    } else {
      failed += 1;
      failures.push({ route, actual, expectedStatus });
    }
  }
} catch (error) {
  console.error(`[verify-deployment-surface] ${error.message}`);
  process.exitCode = 1;
} finally {
  stopServer();
}

console.log('');
console.log(`[verify-deployment-surface] summary: ${passed} passed, ${failed} failed (of ${checks.length} total)`);

if (failed > 0) {
  console.error('');
  console.error('[verify-deployment-surface] FAILURES:');
  for (const f of failures) {
    console.error(`  - ${f.route}: got ${f.actual}, expected ${f.expectedStatus}`);
  }
  console.error('');
  console.error('BAI-SEC-10: deployment surface is leaking or broken. Fix the build artifact and re-run.');
  process.exit(1);
}

process.exit(0);
