#!/usr/bin/env node
/**
 * build-icon-sprite.mjs
 * Step 9 of Migration Closure: Download mdi: icons from Iconify API
 * and build public/icons.svg sprite with <symbol> elements.
 */
import { writeFileSync } from 'node:fs';

const ICONS = [
  'account','account-check','account-cog','account-group','account-lock',
  'account-shield','account-switch','account-tie','alert-circle','alert-triangle',
  'archive-check-outline','arrow-left','arrow-right','bank','bell-concierge',
  'book','brain','briefcase','briefcase-outline','bug','calendar',
  'calendar-check','card-account-details','chart-bar','chart-line','check',
  'check-circle','chevron-down','chevron-left','chip','city','clipboard-check',
  'clipboard-list','clock-outline','cloud-off-outline','cog','cogs','coins',
  'database','domain','download','email','email-open','factory',
  'file-document','file-document-edit','file-document-outline','file-lock',
  'file-pdf-box','file-sign','file-upload','flag','flask','folder-open',
  'gauge','handshake','headset','heart-pulse','home-outline','hospital-building',
  'incognito','information','key','laptop','layers','lightning-bolt',
  'lock','lock-open-variant','magnify','map','map-marker',
  'map-marker-question-outline','map-marker-radius','medical-bag','message-text',
  'newspaper','office-building','play-circle','post','power-plug','puzzle',
  'refresh','robot','scale-balance','school','send','server','share',
  'shield','shield-check','shield-half-full','shield-heart','shield-home',
  'truck-fast','tune','web','whatsapp','wifi-off','wrench'
];

const ICONIFY_API = 'https://api.iconify.design/mdi';

async function downloadIcon(name) {
  const url = `${ICONIFY_API}/${name}.svg`;
  const resp = await fetch(url);
  if (!resp.ok) throw new Error(`Failed to download ${name}: ${resp.status}`);
  const text = await resp.text();
  // Extract the <svg> content — Iconify returns a full <svg> with viewBox and path data
  // We need to extract the inner content (paths, etc.)
  const viewBoxMatch = text.match(/viewBox="([^"]+)"/);
  const viewBox = viewBoxMatch ? viewBoxMatch[1] : '0 0 24 24';
  
  // Extract inner elements (everything between <svg ...> and </svg>)
  const innerMatch = text.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  const inner = innerMatch ? innerMatch[1] : '';
  
  return { name, viewBox, inner };
}

async function main() {
  console.log(`Downloading ${ICONS.length} icons from Iconify...`);
  
  const symbols = [];
  const errors = [];
  
  // Download in batches of 10 to be polite
  for (let i = 0; i < ICONS.length; i += 10) {
    const batch = ICONS.slice(i, i + 10);
    const results = await Promise.allSettled(batch.map(downloadIcon));
    
    for (const result of results) {
      if (result.status === 'fulfilled') {
        symbols.push(result.value);
      } else {
        errors.push(result.reason?.message || 'Unknown error');
      }
    }
    
    if (i + 10 < ICONS.length) {
      await new Promise(r => setTimeout(r, 200)); // rate limit
    }
  }
  
  // Build SVG sprite
  const spriteParts = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!-- BrightAI SVG Icon Sprite — Generated by build-icon-sprite.mjs -->`,
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">`,
  ];
  
  for (const sym of symbols) {
    // Convert kebab-case to a valid symbol id
    const id = `mdi-${sym.name}`;
    // Replace fill="currentColor" patterns and ensure stroke/fill work with CSS
    let content = sym.inner
      .replace(/fill="currentColor"/g, 'fill="currentColor"')
      .replace(/<path /g, '<path ');
    
    spriteParts.push(
      `  <symbol id="${id}" viewBox="${sym.viewBox}">`,
      `    ${content}`,
      `  </symbol>`
    );
  }
  
  spriteParts.push(`</svg>`);
  
  writeFileSync('public/icons.svg', spriteParts.join('\n'), 'utf-8');
  console.log(`Generated public/icons.svg with ${symbols.length} symbols.`);
  
  if (errors.length > 0) {
    console.warn(`\n${errors.length} icons failed to download:`);
    errors.forEach(e => console.warn(`  - ${e}`));
  }
}

main().catch(err => {
  console.error('Build icon sprite failed:', err);
  process.exit(1);
});
