import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('[console.error]', m.text().slice(0, 200)); });
page.on('requestfailed', (r) => console.log('[requestfailed]', r.url(), r.failure() && r.failure().errorText));
await page.goto('http://localhost:4329/kernel/approvals/', { waitUntil: 'load', timeout: 20000 });
await page.waitForTimeout(1500);
console.log('title:', await page.title());
console.log('confirm dialog count:', await page.locator('[data-kernel-confirm]').count());
console.log('toast count:', await page.locator('#k-toast').count());
console.log('KernelFeedback:', await page.evaluate(() => typeof window.KernelFeedback));
console.log('kap card count:', await page.locator('[data-kap-card]').count());
const errs = await page.evaluate(() => window.__errs || null);
await browser.close();
console.log('done');
