import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");

const RENDER_YAML = path.join(ROOT, "render.yaml");
const PUBLIC_HEADERS = path.join(ROOT, "public", "_headers");

/**
 * Parses render.yaml and returns the headers array for the first
 * service. Each entry is { path, name, value }.
 *
 * We parse the YAML manually because we only need the `headers` field
 * and the file is generated by humans (not a build artifact). A full
 * YAML library would add a dependency for no win.
 */
export function parseRenderYamlHeaders(yamlText) {
  const lines = yamlText.split(/\r?\n/);
  const headers = [];
  let inHeaders = false;
  let currentPath = null;
  let currentEntry = null;
  let pendingKey = null;

  for (const line of lines) {
    // Match the start of the headers block.
    if (!inHeaders) {
      if (/^[\s-]*headers:[\s]*$/.test(line)) {
        inHeaders = true;
      }
      continue;
    }

    // We exit the headers block when we hit a sibling top-level key
    // (no leading whitespace) that is NOT a header list item.
    if (inHeaders && line.trim() && !/^\s+/.test(line)) {
      break;
    }

    // Header list item: "- path: /*"
    const pathMatch = line.match(/^\s*-\s+path:\s*(.+?)\s*$/);
    if (pathMatch) {
      if (currentEntry) headers.push(currentEntry);
      currentPath = pathMatch[1];
      currentEntry = { path: currentPath, name: null, value: null };
      pendingKey = null;
      continue;
    }

    // Continuation key under the current entry: "  name: X" or "  value: Y".
    const nameMatch = line.match(/^\s+name:\s*(.+?)\s*$/);
    if (nameMatch && currentEntry) {
      currentEntry.name = nameMatch[1];
      pendingKey = null;
      continue;
    }
    const valueMatch = line.match(/^\s+value:\s*(.+?)\s*$/);
    if (valueMatch && currentEntry) {
      currentEntry.value = unwrapYamlScalar(valueMatch[1]);
      pendingKey = null;
      continue;
    }

    // Continuation of a previous value: "        more-text" (folded scalar).
    // We only fold when the previous value was set and this line starts
    // with 8+ spaces (YAML folded scalar indent).
    if (currentEntry?.value && /^\s{8,}\S/.test(line)) {
      const continuation = line.trim();
      if (continuation) {
        currentEntry.value += " " + unwrapYamlScalarContinuation(continuation);
      }
    }
  }
  if (currentEntry) headers.push(currentEntry);
  return headers;
}

/**
 * Parses public/_headers (Netlify/Cloudflare style) and returns
 * { 'path-glob': { 'header-name': 'value', ... }, ... }.
 *
 * Format (Netlify/Cloudflare Pages spec):
 *   /path-glob
 *     Header-Name: value
 *     Header-Name: value
 *
 *   /another-glob
 *     Header-Name: value
 *
 * A line is a path if it has no leading whitespace, is not a comment
 * (#), and does not contain a colon (Netlify paths are bare globs like
 * `/*`, `/api/*`, or full URLs). A line is a header if it has leading
 * whitespace AND matches the `Name: value` shape. Blank lines and
 * comments end the current rule block.
 */
export function parseNetlifyHeaders(text) {
  const rules = {};
  let currentPath = null;
  let currentHeaders = null;

  const lines = text.split(/\r?\n/);
  const isHeaderLine = (raw) =>
    /^\s+[A-Za-z][A-Za-z0-9-]*\s*:\s*\S/.test(raw);

  for (const raw of lines) {
    const line = raw.replace(/\s+$/, ""); // trim trailing whitespace
    if (!line || line.startsWith("#")) {
      if (currentPath && currentHeaders) {
        rules[currentPath] = currentHeaders;
      }
      currentPath = null;
      currentHeaders = null;
      continue;
    }
    // Header line: indented and matches Name: value shape.
    if (isHeaderLine(raw)) {
      const headerMatch = line.match(/^\s+([A-Za-z0-9-]+):\s*(.*)$/);
      if (headerMatch && currentHeaders !== null) {
        const name = headerMatch[1];
        const value = headerMatch[2];
        currentHeaders[name] = value;
      }
      continue;
    }
    // Otherwise it's a path line (no leading whitespace, no colon, or
    // a path with a glob that has a colon — we treat any non-header,
    // non-blank, non-comment line at column 0 as a new path).
    if (currentPath && currentHeaders) {
      rules[currentPath] = currentHeaders;
    }
    currentPath = line.trim();
    currentHeaders = {};
  }
  if (currentPath && currentHeaders) {
    rules[currentPath] = currentHeaders;
  }
  return rules;
}

/**
 * Returns a flat map of header name → value for a given path glob
 * inside a parsed Netlify/Cloudflare rules object. If multiple rules
 * match, later rules override earlier ones (Netlify convention).
 */
export function headerValueForPath(rules, pathGlob) {
  if (rules[pathGlob]) return rules[pathGlob];
  return null;
}

/**
 * Unwrap a YAML double-quoted scalar. The generator in
 * scripts/sync-headers-from-csp.mjs emits values like
 *   value: "max-age=63072000; includeSubDomains; preload"
 * because the CSP string contains colons, semicolons, and single quotes
 * that are easier to read inside double-quoted YAML. This helper strips
 * the wrapping quotes and unescapes \" and \\ so the parsed value matches
 * the raw value the generator was given.
 *
 * If the input is not a quoted scalar, it is returned unchanged.
 */
function unwrapYamlScalar(raw) {
  if (typeof raw !== "string") return raw;
  if (raw.length < 2) return raw;
  if (raw[0] !== '"' || raw[raw.length - 1] !== '"') return raw;
  // Unescape \" → " and \\ → \. The CSP value does not contain other
  // YAML double-quoted escapes, so the simple state machine is enough.
  let out = "";
  for (let i = 1; i < raw.length - 1; i++) {
    const ch = raw[i];
    if (ch === "\\" && i + 1 < raw.length - 1) {
      const next = raw[i + 1];
      if (next === '"' || next === "\\") {
        out += next;
        i++;
        continue;
      }
    }
    out += ch;
  }
  return out;
}

/**
 * Continuation lines (folded scalars) should be appended verbatim — they
 * are part of an already-unwrapped scalar. But if a generator wrapped a
 * long value across multiple lines (uncommon for our security headers),
 * strip any wrapping quotes from the continuation too. Today no security
 * value is folded across lines, so this is a safety net.
 */
function unwrapYamlScalarContinuation(raw) {
  return unwrapYamlScalar(raw);
}

export function loadRenderYamlHeaders() {
  return parseRenderYamlHeaders(fs.readFileSync(RENDER_YAML, "utf8"));
}

export function loadPublicHeaders() {
  return parseNetlifyHeaders(fs.readFileSync(PUBLIC_HEADERS, "utf8"));
}

export const LAYER_PATHS = {
  renderYaml: RENDER_YAML,
  publicHeaders: PUBLIC_HEADERS,
};
