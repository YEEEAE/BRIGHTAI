#!/usr/bin/env node
/**
 * audit-2026-07-18-syntax.mjs — SyntaxError regression check
 *
 * يفحص كل الصفحات المبنية للتأكد من عدم وجود `<script>...import...</script>`
 * بدون `type="module"` attribute (الـ SyntaxError regression من REPORTS-CSP-01).
 *
 *   BASE_URL=http://127.0.0.1:4321 node scripts/audit-2026-07-18-syntax.mjs
 */

import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';

const BASE_URL = process.env.BASE_URL || 'http://127.0.0.1:4321';

const PAGES = [
  '/',
  '/about/',
  '/pricing/',
  '/solutions/',
  '/kernel/',
  '/kernel/chat/',
  '/blog/',
  '/docs/',
  '/contact/',
  '/trust/',
  '/en/',
  '/en/privacy-policy/',
  '/sales-deck/',
  '/en/sales-deck/',
];

const browser = await chromium.launch();
const results = [];

for (const path of PAGES) {
  const ctx = await browser.newContext();
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push({ type: 'pageerror', msg: e.message }));
  page.on('console', (msg) => {
    if (msg.type() === 'error') errors.push({ type: 'console', msg: msg.text() });
  });
  try {
    const response = await page.goto(BASE_URL + path, { waitUntil: 'networkidle', timeout: 20000 });
    const status = response?.status();
    await page.waitForTimeout(1500);
    results.push({ path, status, syntax_errors: errors.filter((e) => e.msg.includes('import') || e.msg.includes('module')), total_errors: errors.length });
  } catch (e) {
    results.push({ path, error: e.message });
  }
  await ctx.close();
}
await browser.close();

const total_pages = results.length;
const pages_with_syntax = results.filter((r) => r.syntax_errors?.length > 0).length;
const total_syntax_errors = results.reduce((sum, r) => sum + (r.syntax_errors?.length || 0), 0);
const total_errors = results.reduce((sum, r) => sum + (r.total_errors || 0), 0);

const summary = { total_pages, pages_with_syntax, total_syntax_errors, total_errors };

writeFileSync('report/2026-07-18-syntax.json', JSON.stringify({ summary, results }, null, 2));

let md = `# SyntaxError Regression Audit — 2026-07-18\n\n`;
md += `**Base URL**: ${BASE_URL}\n`;
md += `**Pages**: ${total_pages}\n`;
md += `**Pages with SyntaxError**: ${pages_with_syntax} (${Math.round(pages_with_syntax / total_pages * 100)}%)\n`;
md += `**Total SyntaxError events**: ${total_syntax_errors}\n\n`;
md += `## Per-page\n\n| Path | HTTP | SyntaxError events | Total console errors |\n|---|---|---|---|\n`;
for (const r of results) {
  if (r.error) {
    md += `| ${r.path} | — | ERROR | — |\n`;
  } else {
    md += `| ${r.path} | ${r.status} | ${r.syntax_errors?.length || 0} | ${r.total_errors || 0} |\n`;
  }
}
md += `\n_Generated by scripts/audit-2026-07-18-syntax.mjs — Playwright pageerror + console listeners_\n`;

writeFileSync('report/2026-07-18-syntax.md', md);
console.log(md);
