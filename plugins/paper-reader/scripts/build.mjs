import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const plugin = path.resolve(here, '..');
const workspace = path.resolve(plugin, '..', '..');

const worker = await readFile(path.join(plugin, 'vendor', 'pdf.worker.min.mjs'), 'utf8');
const polyfills = await readFile(path.join(plugin, 'src', 'polyfills.js'), 'utf8');
await writeFile(
  path.join(plugin, 'src', 'pdf-worker.generated.js'),
  `/* Generated by scripts/build.mjs. PDF.js worker, Apache-2.0. */\nexport default ${JSON.stringify(`${polyfills}\n${worker}`)};\n`,
  'utf8',
);

const result = await build({
  entryPoints: [path.join(plugin, 'src', 'client.jsx')],
  outfile: path.join(plugin, 'client.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome120', 'safari17', 'firefox120'],
  minify: true,
  legalComments: 'inline',
  external: ['react'],
  loader: { '.js': 'jsx' },
  jsxFactory: 'h',
  jsxFragment: 'h',
  nodePaths: [path.join(workspace, 'node_modules')],
  banner: {
    js: '/*! Paper Reader — DeepSeek Harness plugin. PDF.js is bundled under the Apache-2.0 license; see vendor/LICENSE.pdfjs. */',
  },
});

console.log(`Built client.js (${(await readFile(path.join(plugin, 'client.js'))).byteLength} bytes)`);
for (const warning of result.warnings) console.warn(warning.text);
